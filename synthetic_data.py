import numpy as np
import pandas as pd
from datetime import datetime, timedelta

# Default synthetic pricing according to standard streaming plan structures
PLAN_DETAILS = {
    "Standard with Ads": {"monthly_fee": 6.99, "profiles": [1, 2], "weight": 0.38},
    "Standard": {"monthly_fee": 15.49, "profiles": [1, 2, 3], "weight": 0.42},
    "Premium": {"monthly_fee": 22.99, "profiles": [2, 3, 4, 5], "weight": 0.20},
}

GENRES = [
    "Drama",
    "Action & Thriller",
    "Sci-Fi & Fantasy",
    "Comedy",
    "Docuseries",
    "True Crime",
    "Anime",
    "Reality TV",
]

OFFER_HISTORIES = [
    "None",
    "1_Month_Discount",
    "Ad_Tier_Trial",
    "Plan_Downgrade_Retention",
]


def generate_synthetic_subscribers(n_samples: int = 5000, random_seed: int = 42) -> pd.DataFrame:
    """
    Generates an internally consistent synthetic dataset of fictional streaming subscribers.
    Features include engagement, billing health, customer service friction, and plan details.
    
    Includes a temporal split cutoff (Historical cohort for model training vs Active live cohort).
    """
    rng = np.random.default_rng(random_seed)

    # 1. Subscriber IDs
    sub_ids = [f"NFLX-SYN-{100000 + i}" for i in range(n_samples)]

    # 2. Plan assignments
    plan_names = list(PLAN_DETAILS.keys())
    plan_weights = [PLAN_DETAILS[p]["weight"] for p in plan_names]
    plans = rng.choice(plan_names, size=n_samples, p=plan_weights)
    monthly_fees = np.array([PLAN_DETAILS[p]["monthly_fee"] for p in plans])

    # 3. Tenure (1 to 60 months) with distribution skewed toward newer members
    tenures = rng.geometric(p=0.04, size=n_samples)
    tenures = np.clip(tenures, 1, 60)

    # 4. Cohort Date and Temporal Split Assignment
    # Anchor date: 2026-03-31
    anchor_date = datetime(2026, 3, 31)
    signup_dates = [anchor_date - timedelta(days=int(t * 30.4 + rng.integers(-10, 10))) for t in tenures]
    signup_dates = [max(d, datetime(2021, 1, 1)) for d in signup_dates]

    # Split: Subscribers who joined prior to 2025-10-01 are Historical (used for Train/Test)
    # Subscribers joining after 2025-10-01 or marked as currently active represent the Active Live scoring cohort
    # To create a realistic simulation:
    # 70% historical labeled records (some churned, some retained up to evaluation window)
    # 30% current active subscribers awaiting risk scoring & retention interventions
    is_active_scoring_cohort = rng.random(n_samples) < 0.30

    # 5. Engagement Metrics (30-day window)
    # Correlated active days and viewing hours
    base_activity = rng.beta(a=2.5, b=2.0, size=n_samples)  # 0 to 1
    active_days_30d = np.clip(np.round(base_activity * 28 + rng.normal(0, 2, n_samples)), 0, 30).astype(int)

    # Viewing hours correlates with active days, plan type, and personal habit
    viewing_hours_30d = np.clip(
        active_days_30d * rng.uniform(1.2, 4.8, n_samples) + rng.normal(0, 4, n_samples),
        0.0,
        180.0,
    ).round(1)

    # Days since last session (inactivity signal)
    # Higher for people with lower active days
    days_since_last_session = np.where(
        active_days_30d == 0,
        rng.integers(31, 75, n_samples),
        np.clip(np.round((30 - active_days_30d) * rng.uniform(0.1, 0.9, n_samples)), 0, 30).astype(int),
    )

    # Content completion rate (fraction of started titles finished >= 70%)
    content_completion_rate = np.clip(
        0.30 + (viewing_hours_30d / 200.0) * 0.45 + rng.normal(0, 0.12, n_samples),
        0.05,
        0.98,
    ).round(2)

    # 6. Technical & Friction Metrics
    # Failed payments in last 90 days (dunning signals: 0, 1, 2, 3+)
    # Base probability of payment issue is higher for newer tenures or specific payment methods
    failed_payment_prob = np.clip(0.08 + (tenures < 4) * 0.08 - (viewing_hours_30d > 50) * 0.03, 0.02, 0.35)
    failed_payments_90d = rng.poisson(lam=failed_payment_prob, size=n_samples)
    failed_payments_90d = np.clip(failed_payments_90d, 0, 4)

    # Customer Support Contacts in last 6 months
    support_contacts_6m = rng.poisson(lam=0.9 + (failed_payments_90d * 0.8), size=n_samples)
    support_contacts_6m = np.clip(support_contacts_6m, 0, 8)

    # Formal complaints logged (escalations, streaming quality, billing disputes)
    complaints_logged = np.where(
        support_contacts_6m >= 2,
        rng.choice([0, 1, 2], size=n_samples, p=[0.70, 0.22, 0.08]),
        np.zeros(n_samples, dtype=int),
    )

    # 7. Profile & Device Topology
    profiles = []
    for p in plans:
        allowed = PLAN_DETAILS[p]["profiles"]
        profiles.append(int(rng.choice(allowed)))
    profile_count = np.array(profiles)

    device_count = np.clip(profile_count + rng.integers(0, 3, n_samples), 1, 6)
    downloads_used_30d = np.where(
        plans == "Standard with Ads",
        np.zeros(n_samples, dtype=int),  # Ads tier historically had limited download support
        np.clip(rng.poisson(lam=3.5, size=n_samples), 0, 25),
    )

    # 8. Preferences & Marketing
    primary_genres = rng.choice(GENRES, size=n_samples)
    offer_histories = rng.choice(OFFER_HISTORIES, size=n_samples, p=[0.68, 0.16, 0.10, 0.06])

    # 9. Synthetic Ground Truth Churn Log-Odds Formula (tailored latent probability)
    # Calibrated to produce realistic streaming cohort dynamics:
    # ~52% Low Risk (<20%), ~34% Medium Risk (20-49%), ~10% High Risk (50-74%), ~5% Critical Risk (>=75%)
    plan_risk_bias = np.where(plans == "Standard with Ads", 0.18, np.where(plans == "Premium", -0.10, 0.0))
    offer_bias = np.where(offer_histories == "Plan_Downgrade_Retention", 0.25, 0.0)

    log_odds = (
        -1.55
        + (days_since_last_session - 10) * 0.075
        + (40.0 - viewing_hours_30d) * 0.028
        + (0.50 - content_completion_rate) * 1.80
        + (failed_payments_90d * 1.50)
        + (support_contacts_6m * 0.25)
        + (complaints_logged * 0.80)
        - (np.log1p(tenures) - 2.5) * 0.30
        - (profile_count - 2.0) * 0.25
        - (device_count - 2.5) * 0.15
        + plan_risk_bias
        + offer_bias
        + rng.normal(0, 0.35, n_samples)  # Unobserved real-world variance
    )

    churn_prob_latent = 1.0 / (1.0 + np.exp(-log_odds))
    churn_prob_latent = np.clip(churn_prob_latent, 0.01, 0.99)

    # 10. Labeled outcomes:
    # For historical records, churn_label is observed outcome (1 = cancelled, 0 = active/renewed)
    # For active cohort records, churn_label is simulated ground-truth for held-out validation or scoring
    churn_outcomes = (rng.random(n_samples) < churn_prob_latent).astype(int)

    # For the active live cohort, they are currently still paying, but their risk needs to be forecasted!
    cohort_status = np.where(is_active_scoring_cohort, "Active (To Score)", "Historical (Train/Test)")
    observed_churn = np.where(is_active_scoring_cohort, np.nan, churn_outcomes)

    df = pd.DataFrame(
        {
            "subscriber_id": sub_ids,
            "cohort_status": cohort_status,
            "signup_date": signup_dates,
            "tenure_months": tenures,
            "plan_type": plans,
            "monthly_fee": monthly_fees,
            "viewing_hours_30d": viewing_hours_30d,
            "active_days_30d": active_days_30d,
            "days_since_last_session": days_since_last_session,
            "content_completion_rate": content_completion_rate,
            "failed_payments_90d": failed_payments_90d,
            "support_contacts_6m": support_contacts_6m,
            "complaints_logged": complaints_logged,
            "offer_history": offer_histories,
            "primary_genre": primary_genres,
            "profile_count": profile_count,
            "device_count": device_count,
            "downloads_used_30d": downloads_used_30d,
            "latent_churn_prob": churn_prob_latent.round(4),
            "churn_label": churn_outcomes,  # Latent ground truth
            "observed_churn": observed_churn,  # Labeled for historical, NaN for active
            "data_tag": "SYNTHETIC_DATA_DEMO",
        }
    )

    return df


